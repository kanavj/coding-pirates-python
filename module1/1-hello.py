# print() shows text on the screen
print("Hello!")

# A variable is a box with a name. The = puts a value in the box.
name = "Elastigirl"  # text (a string) goes inside quotes
real_name = "Helen Parr"
age = 40  # a number has no quotes
married = True  # True or False (a boolean)
husband = "Mr. Incredible"
kids = ["Violet", "Dash", "Jack-Jack"]  # a list holds many values
superpower = "stretching"

print("Name:", name)
print("Real name:", real_name)
print("Age:", age)
print("Married:", married)
print("Husband:", husband)
print("Kids:", kids)
print("Superpower:", superpower)

# You can do maths with numbers
print("Next year she will be", age + 1)

